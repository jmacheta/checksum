// Fills data with the message: the low byte of each xorshift32 step from 0x12345678.
constexpr void fill_message(std::span<std::byte> data) {
  std::uint32_t state = 0x12345678U;
  for(auto &byte : data) {
    state ^= state << 13U;
    state ^= state >> 17U;
    state ^= state << 5U;
    byte = static_cast<std::byte>(state);
  }
}

